/**
 * Подписи народа и вида центра на татарской версии. Сами карточки на
 * татарский не переводятся: значения остаются русскими (по ним работают
 * фильтры), меняется только то, что видит читатель.
 */
const ttLabels: Record<string, string> = {
	Татарский: "Татар",
	"Татаро-Башкирский": "Татар-башкорт",
	Башкирский: "Башкорт",
	Крымотатарский: "Кырым татар",
	"Регион РФ": "Россия төбәге",
	Зарубежный: "Чит ил",
	Онлайн: "Онлайн",
};

export function getCenterValueLabel(value: string, locale: string): string {
	return locale === "tt" ? (ttLabels[value] ?? value) : value;
}
