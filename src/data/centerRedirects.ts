/**
 * Карточки центров, слитые в другую при дедупликации: `удалённый id → id,
 * в который влит`. Номер `tbk-N` — постоянный адрес, на него ссылаются
 * поиск, закладки и соцсети, поэтому удалённая карточка не исчезает, а
 * переадресует на оставшуюся. Повторно эти номера не занимать.
 *
 * Сливая дубль: перенеси все факты, ссылки и источники в оставшуюся
 * карточку (RU и EN), удали оба файла дубля и допиши строку сюда.
 */
export const mergedCenters: Record<string, string> = {
	// 2026-10-02, аудит карточек: одна организация под двумя записями.
	"tbk-192": "tbk-39", // «Ильдаш», Алматы
	"tbk-25": "tbk-184", // «Дуслык», Петропавловск
	"tbk-87": "tbk-339", // «Мирас», Вена
	"tbk-37": "tbk-29", // «Идел», Алматы
	"tbk-187": "tbk-29", // ТБОКЦ Алматы — тот же центр «Идел», ул. Уалиханова, 63
	"tbk-281": "tbk-258", // Instagram @tatardiaspora.kg — аккаунт «Туган тел»
	"tbk-271": "tbk-220", // «Татары в Бельгии»
	"tbk-207": "tbk-38", // «Идель», Эстония: город Тарту был ошибкой справочника ВКТ
	"tbk-58": "tbk-15", // «Чишмэ», Рига: один регномер 40008055524
};

/** Пары «старый путь → новый» для `redirects` в astro.config, обе локали. */
export function centerRedirects(): Record<string, string> {
	const routes: Record<string, string> = {};
	for (const [from, to] of Object.entries(mergedCenters)) {
		routes[`/centers/${from}`] = `/centers/${to}`;
		routes[`/en/centers/${from}`] = `/en/centers/${to}`;
	}
	return routes;
}
